/* Builds rules/rules.bundle.js from the ES modules in rules/.
   Run from the repo folder:  npm run build   (or: node tools/build-rules.js)
   Why: browsers will not load ES modules from a page opened by double-click (file://).
   The bundle is one plain script that sets the global EP, so index.html still works by double-click.
   Node tests and Base44 use the modules (rules/index.js). Tests/check_bundle.js fails if the bundle is out of date.

   How: the module list and order come from rules/index.js. Each module becomes
     const Name = (() => { ...module code, minus import/export lines...; return Name; })();
   Each module keeps its own scope, so helper names like KEYS can repeat across files. */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const RULES = path.join(ROOT, "rules");
const OUT = path.join(RULES, "rules.bundle.js");

function modules() {
  const index = fs.readFileSync(path.join(RULES, "index.js"), "utf8");
  const list = [...index.matchAll(/^export \{ (\w+) \} from "\.\/(\w+)\.js";$/gm)].map(m => ({ name: m[1], file: m[2] + ".js" }));
  if (!list.length) throw new Error("rules/index.js lists no modules");
  return list;
}

function buildBundle() {
  const list = modules();
  const parts = list.map(({ name, file }) => {
    const src = fs.readFileSync(path.join(RULES, file), "utf8").replace(/\r\n/g, "\n");
    const exportLine = "export { " + name + " };";
    if (!src.split("\n").includes(exportLine)) throw new Error(file + ": missing '" + exportLine + "'");
    const body = src.split("\n")
      .filter(l => !/^import \{ [\w, ]+ \} from "\.\/\w+\.js";$/.test(l) && l !== exportLine)
      .join("\n").trimEnd();
    if (/^\s*(import|export)\b/m.test(body)) throw new Error(file + ": import or export in an unexpected form");
    return "/* ---------- rules/" + file + " ---------- */\nconst " + name + " = (() => {\n" + body + "\nreturn " + name + ";\n})();\n";
  });
  return "/* GENERATED by tools/build-rules.js from rules/*.js. Do not edit this file.\n"
    + "   After changing any rule file, run: npm run build */\n"
    + "(function () {\n\"use strict\";\n\n" + parts.join("\n")
    + "\nglobalThis.EP = Object.assign(globalThis.EP || {}, { " + list.map(m => m.name).join(", ") + " });\n})();\n";
}

module.exports = { buildBundle, modules, OUT };

if (require.main === module) {
  fs.writeFileSync(OUT, buildBundle());
  console.log("Wrote " + path.relative(ROOT, OUT) + " from " + modules().length + " modules.");
}
